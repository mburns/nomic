const fs = require("node:fs");
const path = require("node:path");

function parseRuleFile(filePath) {
	const content = fs.readFileSync(filePath, "utf-8");

	// Extract frontmatter
	const frontmatterMatch = content.match(/^---\n([\s\S]*?)\n---/);
	if (!frontmatterMatch) {
		return null;
	}

	const frontmatter = frontmatterMatch[1];
	const ruleContent = content.replace(/^---\n[\s\S]*?\n---\n/, "");

	// Parse frontmatter
	const metadata = {};
	frontmatter.split("\n").forEach((line) => {
		const [key, ...valueParts] = line.split(":");
		if (key && valueParts.length > 0) {
			metadata[key.trim()] = valueParts.join(":").trim();
		}
	});

	// Extract title from content
	const titleMatch = ruleContent.match(/^# (.*)$/m);
	const title = titleMatch ? titleMatch[1] : path.basename(filePath, ".md");

	// Extract rule text (everything after the title, before copyright)
	let ruleText = ruleContent.replace(/^# .*$/m, "").trim();
	const copyrightIndex = ruleText.indexOf("# Copyright");
	if (copyrightIndex !== -1) {
		ruleText = ruleText.substring(0, copyrightIndex).trim();
	}

	return {
		id: metadata.RULE || path.basename(filePath, ".md"),
		title,
		author: metadata.Author || "Unknown",
		status: metadata.Status || "Unknown",
		type: metadata.Type || "Unknown",
		tags: metadata.Tags ? metadata.Tags.split(",").map((t) => t.trim()) : [],
		content: ruleText,
		filename: path.basename(filePath),
	};
}

function linkToRule(rule) {
	return `[${rule.id}](rules/${rule.filename})`;
}

function codeTag(tag) {
	return `\`${tag}\``;
}

function linkTag(tag) {
	return `[\`${tag}\`](#tag-${tag.replace(/[^a-zA-Z0-9]/g, "").toLowerCase()})`;
}

function getRecentUpdateBadge(ruleId) {
	const recentRules = {
		308: " [#46](https://github.com/mburns/nomic/pull/46)",
		309: " [#46](https://github.com/mburns/nomic/pull/46)",
		101: " [#40](https://github.com/mburns/nomic/pull/40)",
	};
	return recentRules[ruleId] || "";
}

function generateRulesSummary() {
	const rulesDir = path.join(__dirname, "..", "rules");
	const outputFile = path.join(__dirname, "..", "RULES_SUMMARY.md");

	if (!fs.existsSync(rulesDir)) {
		console.error("Rules directory not found:", rulesDir);
		process.exit(1);
	}

	const ruleFiles = fs
		.readdirSync(rulesDir)
		.filter((file) => file.endsWith(".md"))
		.sort((a, b) => {
			// Extract rule numbers for sorting
			const aNum = parseInt(a.match(/rule(\d+)\.md/)?.[1] || "0");
			const bNum = parseInt(b.match(/rule(\d+)\.md/)?.[1] || "0");
			return aNum - bNum;
		});

	const rules = [];
	const errors = [];

	ruleFiles.forEach((file) => {
		try {
			const rule = parseRuleFile(path.join(rulesDir, file));
			if (rule) {
				rules.push(rule);
			} else {
				errors.push(`Failed to parse ${file}: No frontmatter found`);
			}
		} catch (error) {
			errors.push(`Failed to parse ${file}: ${error.message}`);
		}
	});

	// Collect tag info
	const tagMap = {};
	rules.forEach((rule) => {
		rule.tags.forEach((tag) => {
			if (!tagMap[tag]) tagMap[tag] = [];
			tagMap[tag].push(rule);
		});
	});
	const allTags = Object.keys(tagMap).sort();

	// Statistics
	const stats = {
		total: rules.length,
		immutable: rules.filter((r) => r.type === "Immutable").length,
		mutable: rules.filter((r) => r.type === "Mutable").length,
		active: rules.filter((r) => r.status === "Accepted").length,
		draft: rules.filter((r) => r.status === "Draft").length,
		tags: allTags.length,
		authors: new Set(rules.map((r) => r.author)).size,
	};

	// Generate summary content
	let summary = `# Nomic Rules Summary

This document provides a comprehensive overview of all rules in the Nomic game. This file is automatically generated from the \`rules/\` directory.

## Rule Statistics

| Statistic         | Count |
|-------------------|-------|
| Total Rules       | ${stats.total} |
| Immutable Rules   | ${stats.immutable} |
| Mutable Rules     | ${stats.mutable} |
| Active Rules      | ${stats.active} |
| Draft Rules       | ${stats.draft} |
| Unique Tags       | ${stats.tags} |
| Unique Authors    | ${stats.authors} |

## Tag Index

${allTags.length === 0 ? "No tags found." : allTags.map((tag) => `- <a id="tag-${tag.replace(/[^a-zA-Z0-9]/g, "").toLowerCase()}"></a>${codeTag(tag)} (${tagMap[tag].length})`).join("\n")}

## Detailed Rule List

`;

	// Add each rule with full details
	rules.forEach((rule) => {
		summary += `### Rule ${linkToRule(rule)}: ${rule.title}${getRecentUpdateBadge(rule.id)}

**Type**: ${rule.type}  
**Status**: ${rule.status}  
**Author**: ${rule.author}  
**Tags**: ${rule.tags.length ? rule.tags.map(linkTag).join(", ") : "None"}

${rule.content}

---
`;
	});

	// Add any parsing errors
	if (errors.length > 0) {
		summary += `\n## Parsing Errors

The following files could not be parsed:

${errors.map((error) => `- ${error}`).join("\n")}
`;
	}

	// Add footer
	summary += `
---

*This file was automatically generated on ${new Date().toISOString()}. Any changes to the \`rules/\` directory will regenerate this file.*
`;

	// Write the summary file
	fs.writeFileSync(outputFile, summary);
	console.log(`Generated rules summary: ${outputFile}`);
	console.log(`Processed ${rules.length} rules`);

	if (errors.length > 0) {
		console.warn(`Warnings: ${errors.length} files had parsing issues`);
	}
}

// Run the generator
generateRulesSummary();
